def _smoke_test(slug: str) -> str:
    return f'''"""Smoke test: validates project wiring without heavy computation.

These tests must pass before any real experiment (see validation stage).
They check configuration parsing, module imports, and (when implemented)
that the pipeline runs end-to-end on a tiny input.
"""

import importlib
import os
import sys
import unittest

_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(_ROOT, "src"))


class SmokeTests(unittest.TestCase):
    def test_config_loads(self):
        import yaml

        with open("config.yaml", encoding="utf-8") as f:
            cfg = yaml.safe_load(f)
        self.assertIn("hyperparameters", cfg)
        self.assertIn("requirements", cfg)

    def test_modules_import(self):
        for mod in ("{slug.replace('-', '_')}.model",
                    "{slug.replace('-', '_')}.data",
                    "{slug.replace('-', '_')}.train"):
            importlib.import_module(mod)

    def test_build_model_signature(self):
        from {slug.replace('-', '_')}.model import build_model

        import yaml

        with open("config.yaml", encoding="utf-8") as f:
            cfg = yaml.safe_load(f)
        try:
            build_model(cfg)
        except NotImplementedError:
            pass  # scaffold not yet implemented: expected in generated project
        except Exception as e:  # pragma: no cover
            self.fail(f"build_model raised unexpected error: {{e}}")


if __name__ == "__main__":
    unittest.main(verbosity=2)
'''


def _run_smoke(slug: str) -> str:
    return """#!/usr/bin/env bash
# Research RAG smoke run: syntax check + generated unit tests.
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")"
"${PYTHON_BIN:-python}" -m compileall -q .
"${PYTHON_BIN:-python}" tests/test_smoke.py
echo SMOKE_OK
"""


def _readme(spec: ImplementationSpec, slug: str) -> str:
    reqs = spec.requirements
    by_source: dict[str, list] = {}
    for r in reqs:
        by_source.setdefault(r.source.value, []).append(r)
    lines = [
        f"# {slug.replace('-', ' ').title()}",
        "",
        f"Generated implementation project for **{spec.title}**.",
        "",
        "## Specification",
        "",
        spec.summary,
        "",
        f"Built from spec `{spec.id}` with {len(reqs)} requirements "
        f"({len(by_source.get('explicit', []))} explicit, "
        f"{len(by_source.get('inferred', []))} inferred).",
        "",
        "## Layout",
        "",
        "```",
        "config.yaml           # hyperparameters + requirement traceability",
        "src/{slug.replace('-', '_')}/       # model, data, train, evaluate, infer",
        "tests/test_smoke.py   # smoke tests (must pass before experiments)",
        "run_smoke.sh          # syntax check + smoke tests",
        "```",
        "",
        "## Usage",
        "",
        "```bash",
        "pip install -r requirements.txt",
        "./run_smoke.sh",
        "```",
        "",
        "## Open questions (paper does not specify)",
        "",
    ]
    if spec.open_questions:
        lines += [f"- {q}" for q in spec.open_questions]
    else:
        lines.append("- (none recorded)")
    lines += ["", "## Provenance", ""]
    for r in reqs[:20]:
        page = f" p.{r.source_page}" if r.source_page else ""
        lines.append(f"- **{r.id}** [{r.source.value}]{page}: {r.requirement}")
    if len(reqs) > 20:
        lines.append(f"- … and {len(reqs) - 20} more (see config.yaml)")
    return "\n".join(lines) + "\n"


def _requirements_txt(spec: ImplementationSpec) -> str:
    deps = list(spec.dependencies)
    base = ["pyyaml"]
    out = sorted(set(base + [d.split("==")[0].strip() for d in deps]))
    return "\n".join(out) + "\n"


