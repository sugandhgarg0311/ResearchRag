def generate_scaffold(spec: ImplementationSpec) -> list[GeneratedFile]:
    slug = project_slug(spec.title)
    pkg = slug.replace("-", "_")
    files = [
        GeneratedFile("README.md", _readme(spec, slug), kind="doc"),
        GeneratedFile("requirements.txt", _requirements_txt(spec), kind="deps"),
        GeneratedFile("config.yaml", _config_yaml(spec), kind="config"),
        GeneratedFile(f"src/{pkg}/__init__.py", f'"""{slug} (generated project)."""\n'),
        GeneratedFile(f"src/{pkg}/model.py", _model_py(spec, slug), kind="source"),
        GeneratedFile(f"src/{pkg}/data.py", _data_py(spec, slug), kind="source"),
        GeneratedFile(f"src/{pkg}/train.py", _train_py(spec, slug), kind="source"),
        GeneratedFile(f"src/{pkg}/evaluate.py", _evaluate_py(slug), kind="source"),
        GeneratedFile(f"src/{pkg}/infer.py", _infer_py(slug), kind="source"),
        GeneratedFile("tests/test_smoke.py", _smoke_test(slug), kind="test"),
        GeneratedFile("run_smoke.sh", _run_smoke(slug), kind="script"),
        GeneratedFile(".gitignore", "__pycache__/\n*.pyc\n.venv/\n"),
    ]
    return files
