"""Deterministic project scaffolding from an ImplementationSpec.

The scaffold is a *real, runnable* project skeleton:

* config.yaml carries every hyperparameter requirement as a key with its
  requirement id (traceability: config → spec requirement → paper page),
* source modules are structured with TODO(REQ-xxx) markers where the
  paper requires an implementation decision,
* tests/test_smoke.py and run_smoke.sh are genuinely executable and are
  used by the validation stage,
* values the paper does NOT specify are left as null with a comment —
  never invented.

An LLM can later regenerate/fill individual files (see generator.py); the
scaffold format is stable either way.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

from researchrag.models.retrieval import (
    ImplementationSpec,
    RequirementType,
)


def project_slug(title: str | None) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", (title or "paper").lower()).strip("-")
    return slug[:48] or "paper"


@dataclass
class GeneratedFile:
    path: str
    content: str
    kind: str = "source"  # source | config | test | script | doc | deps


