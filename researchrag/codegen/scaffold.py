def _requirements_block(spec: ImplementationSpec, rtype: RequirementType) -> str:
    reqs = spec.requirements_by_type(rtype)
    if not reqs:
        return "    # (none extracted — review the paper manually)\n"
    out = []
    for r in reqs:
        page = f" p.{r.source_page}" if r.source_page else ""
        out.append(f"    # {r.id} [{r.source.value}]{page} {r.requirement}\n")
    return "".join(out)


