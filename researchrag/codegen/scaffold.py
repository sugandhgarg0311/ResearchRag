def _config_yaml(spec: ImplementationSpec) -> str:
    lines = [
        "# Generated by Research RAG from implementation spec",
        f"# Spec: {spec.id}",
        "# Each key is tagged with the spec requirement id it came from",
        "# (REQ-xxx) and its provenance. null = not specified in the paper.",
        "",
        "paper:",
        f'  title: "{spec.title}"',
        "",
        "requirements:",
    ]
    reqs = spec.requirements
    if not reqs:
        lines.append("  {}")
    for r in reqs:
        value = _requirement_value(r)
        lines.append(f"  # {r.id} [{r.type.value}/{r.source.value}] {r.requirement}")
        if r.source_page:
            lines.append(f"  #   source: p.{r.source_page} {r.source_section or ''}".rstrip())
        if r.source_quote:
            lines.append(f'  #   quote: "{r.source_quote[:100]}"')
        lines.append(f"  - id: {r.id}")
        lines.append(f"    type: {r.type.value}")
        lines.append(f"    source: {r.source.value}")
        lines.append(f'    statement: "{_yaml_escape(r.requirement)}"')
        lines.append(f"    value: {_yaml_value(value)}")
        lines.append("")
    lines += [
        "hyperparameters:",
        "  # null means: the paper does not specify this — decide and document it.",
    ]
    hp = spec.requirements_by_type(RequirementType.HYPERPARAMETER)
    found: dict[str, str] = {}
    for r in hp:
        found[r.requirement.lower()] = r.requirement
    defaults = [
        "learning_rate",
        "batch_size",
        "weight_decay",
        "warmup_steps",
        "dropout",
        "top_k",
        "seed",
    ]
    for key in defaults:
        matched = next(
            (
                r
                for r in hp
                if key.split("_")[0] in r.requirement.lower()
            ),
            None,
        )
        if matched:
            val = _requirement_value(matched)
            lines.append(
                f"  {key}: {_yaml_value(val)}  # {matched.id} ({matched.source.value})"
            )
        else:
            lines.append(f"  {key}: null  # not specified in paper")
    return "\n".join(lines) + "\n"


def _requirement_value(r) -> str | None:
    m = re.search(r":\s*([0-9eE.\-+]+|[\w\-]+)\s*$", r.requirement)
    if m:
        return m.group(1)
    return None


def _yaml_value(v: str | None) -> str:
    if v is None:
        return "null"
    try:
        float(v)
        return v
    except ValueError:
        return f'"{v}"'


def _yaml_escape(s: str) -> str:
    return s.replace('"', "'")


